// Extract the built-in Jatiya (Bangla National) layout from BuiltInLayouts.kt
// into src/assets/layouts/bn_jatiya.wmlayout.json for the homepage's
// LayoutExplorer. Purely mechanical: all Bengali strings are copied
// byte-for-byte from the Kotlin source, never retyped, so composed/decomposed
// normalization cannot drift. Re-run (node scripts/extract-jatiya.mjs) if the
// built-in layout changes.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const DOCS = dirname(dirname(fileURLToPath(import.meta.url)));
const REPO = dirname(DOCS);
const KT = join(REPO, 'core/language/src/main/java/com/wasimaster/wmkeyboard/core/layout/BuiltInLayouts.kt');
const BPY = join(REPO, 'app/src/main/assets/layouts/bpy_bengali.wmlayout.json');
const OUT_DIR = join(DOCS, 'src/assets/layouts');
const OUT = join(OUT_DIR, 'bn_jatiya.wmlayout.json');

const src = readFileSync(KT, 'utf8');

// The display name from the JATIYA LayoutSpec.
const specBlock = src.slice(src.indexOf('val JATIYA = LayoutSpec('));
const name = specBlock.match(/name = "([^"]+)"/)[1];

// The rows block: from `private val jatiyaRows` to the closing top-level `)`.
const start = src.indexOf('private val jatiyaRows = listOf(');
const end = src.indexOf('\n)', start);
const block = src.slice(start, end);

// Rows are the depth-1 `listOf(...)` groups inside the block.
const rowTexts = [];
let depth = 0;
let rowStart = -1;
for (let i = 0; i < block.length; i++) {
	if (block.startsWith('listOf(', i)) {
		depth++;
		if (depth === 2 && rowStart === -1) rowStart = i; // depth 1 is the outer listOf
		i += 'listOf('.length - 1;
		continue;
	}
	if (block[i] === '(') depth++;
	if (block[i] === ')') {
		depth--;
		if (depth === 1 && rowStart !== -1) {
			rowTexts.push(block.slice(rowStart, i + 1));
			rowStart = -1;
		}
	}
}

const KEY_RE =
	/Key\(\s*"((?:[^"\\]|\\.)*)"(?:,\s*shiftLabel\s*=\s*"((?:[^"\\]|\\.)*)")?(?:,\s*longPress\s*=\s*listOf\(([^)]*)\))?(?:,\s*action\s*=\s*KeyAction\.(\w+))?(?:,\s*width\s*=\s*([\d.]+)f)?\s*\)/g;

const rows = rowTexts.map((text) => {
	const keys = [];
	for (const m of text.matchAll(KEY_RE)) {
		const [, label, shiftLabel, longPress, action, width] = m;
		const key = { label };
		if (shiftLabel) key.shiftLabel = shiftLabel;
		if (longPress) key.longPress = [...longPress.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((x) => x[1]);
		if (action) key.action = { type: action.toLowerCase() };
		if (width) key.width = Number(width);
		keys.push(key);
	}
	return keys;
});

if (rows.length !== 3) throw new Error(`expected 3 letter rows, got ${rows.length}`);
if (rows.map((r) => r.length).join() !== '10,9,9') {
	throw new Error(`unexpected row sizes: ${rows.map((r) => r.length)}`);
}

// Bottom row comes verbatim from a shipped asset layout (same for all).
const bpy = JSON.parse(readFileSync(BPY, 'utf8'));
const bottom = bpy.layout.layers.letters.rows.at(-1);

const out = {
	format: 'wmkeyboard-layout',
	version: 1,
	_source:
		'Generated by docs/scripts/extract-jatiya.mjs from BuiltInLayouts.kt jatiyaRows; regenerate if the built-in layout changes.',
	layout: {
		id: 'docs_bn_jatiya',
		name,
		langId: 'bn',
		version: 1,
		layers: { letters: { rows: [...rows, bottom] } },
	},
};

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');

// Sanity: every extracted label must exist verbatim in one of the sources.
const check = JSON.parse(readFileSync(OUT, 'utf8'));
const flat = check.layout.layers.letters.rows.flat().map((k) => k.label).join('');
const ok = [...flat].every(
	(ch) => ch === ' ' || src.includes(ch) || bpy.layout.layers.letters.rows.flat().some((k) => k.label.includes(ch)),
);
if (!ok) throw new Error('extracted a character not present in the sources');
console.log('wrote', OUT, '| name:', check.layout.name, '| rows:', check.layout.layers.letters.rows.map((r) => r.length).join(','));
